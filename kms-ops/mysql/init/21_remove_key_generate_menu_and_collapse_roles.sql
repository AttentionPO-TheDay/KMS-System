-- =============================================================================
-- 21_remove_key_generate_menu_and_collapse_roles.sql
-- -----------------------------------------------------------------------------
-- 本脚本对应重构计划 P1（D1 / D13）在数据库侧的改动，共三件事：
--
--   1. 删除管理端「密钥生成」菜单（menu_id = 4000 及其按钮级子项）。
--      决策原文：「生成它不需要」—— 管理员只做密钥的更新与回收。
--      同时移除了「用户密钥池」页内的生成按钮与表单弹窗（前端已改），
--      所以这里删掉的是一条已经不再有入口的能力，不会留下「菜单没了但功能还在」。
--
--   2. 角色等级由 3 级收成 2 级（D13）：0=管理员、2=普通用户。
--      历史上 1=「中级用户」，其**唯一**用途是放行 PUBLIC_KEY_LIST；
--      该功能已按 D1 整体删除，等级 1 随之废弃。
--      当前库中已确认不存在 role_level = 1 的账号，本语句是防御性迁移。
--
--   3. 清理生成域遗留的权限申请（system_code = 'generate'）。
--      生成域整套权限子系统（接口 / 服务 / Mapper / 定时任务）已随之删除，
--      这些记录再无任何界面或接口可以读到，属于不可达的孤儿数据。
--
-- 幂等：全部为 DELETE / UPDATE，可重复执行。
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. 删除「密钥生成」菜单
-- ---------------------------------------------------------------------------
-- 4000 = 密钥管理(9001) 下的「密钥生成」，component = generate/index
-- 2002 = 其下唯一的按钮级子项
DELETE FROM sys_role_menu WHERE menu_id IN (4000, 2002);
DELETE FROM sys_menu      WHERE menu_id IN (4000, 2002);

-- ---------------------------------------------------------------------------
-- 2. 角色等级收成 2 级
-- ---------------------------------------------------------------------------
UPDATE sys_user SET role_level = 2 WHERE role_level = 1;

-- 备注文案里若仍写「中级用户 / 3 级」，一并更正，避免后来者按旧模型理解
UPDATE sys_user SET remark = CONCAT(IFNULL(remark, ''), ' [角色模型已收成 2 级：0=管理员/2=普通用户]')
WHERE role_level = 1 AND IFNULL(remark, '') NOT LIKE '%角色模型已收成 2 级%';

-- ---------------------------------------------------------------------------
-- 3. 清理生成域遗留权限申请
-- ---------------------------------------------------------------------------
DELETE FROM permission_request WHERE system_code = 'generate';

-- ---------------------------------------------------------------------------
-- 4. 结果自检（在 mysql 客户端中会打印，便于确认）
-- ---------------------------------------------------------------------------
SELECT '残留的密钥生成菜单（应为 0）' AS check_item, COUNT(*) AS actual
FROM sys_menu WHERE menu_id IN (4000, 2002);

SELECT '残留的 1 级账号（应为 0）' AS check_item, COUNT(*) AS actual
FROM sys_user WHERE role_level = 1;

SELECT '残留的生成域权限申请（应为 0）' AS check_item, COUNT(*) AS actual
FROM permission_request WHERE system_code = 'generate';