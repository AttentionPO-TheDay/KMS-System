-- 把菜单「节点鉴权」改名为「节点分发授权」。
--
-- 为什么改（用户 2026-09-24 反馈）
-- -------------------------------
-- 「节点鉴权」这个名字让人以为它是"普通用户申请提高自己的权限"，
-- 但那个功能是**另一个页面**（权限与审计 → 权限审批 → 权限申请，
-- menu_id=8002，后端 `/permission/request/*`）。
-- 本菜单（9005/9006）实际做的是：**管理员把分发节点授权给某个用户**，
-- 决定他能向哪些节点分发密钥（P3-10 / D5）。
--
-- 名字对不上，代价是实打实的：用户会去错的页面找功能，然后以为系统缺了东西。
-- 所以这里改成一个说了就懂的词，并在页面上写明它管的是"谁能向哪些节点分发"，
-- 同时指出"提权申请"在权限申请那一页。
--
-- 功能一行未动，只改名字。幂等。
-- =============================================================================

-- ⚠️ 必须有这一行（2026-09-30 补）：本文件含中文，而**管道导入**
--    （docker-entrypoint-initdb.d / docker exec -i ... mysql < file）时
--    客户端字符集不保证是 utf8mb4。缺了它中文会按单字节解析后再以 utf8mb4 存储，
--    即**双重编码** —— 库里存的是 C3A5C2B7... 这类字节，前端渲染成「å·¥ä½œå°」。
--    本文件此前正因缺这一行，把 20 个菜单名写坏（由 42_*.sql 修复）。
SET NAMES utf8mb4;

UPDATE sys_menu SET menu_name = '节点分发授权'
WHERE menu_id IN (9005, 9006);

-- 父级目录上顺手标注归属，避免再被当成"区块链节点管理"
UPDATE sys_menu SET remark = '管理员把分发节点授权给用户（决定其可向哪些节点分发）；不是提权申请，也不是区块链节点'
WHERE menu_id = 9005;

UPDATE sys_menu SET remark = '授权关系列表（数据在分发模块 falcon_kds，与链无关）'
WHERE menu_id = 9006;

-- 排查用：如果这里只剩一行，说明 25_*.sql 没跑过（菜单不存在），页面将无法从侧边栏进入
SELECT '节点授权菜单' AS check_item, menu_id, menu_name FROM sys_menu WHERE menu_id IN (9005, 9006);

-- 对照：这才是"普通用户申请提权"的页面
SELECT '提权申请页（另一个功能）' AS check_item, menu_id, menu_name, path, component
FROM sys_menu WHERE menu_id IN (8001, 8002);