-- =============================================================================
-- 24_reset_legacy_key_data.sql
-- -----------------------------------------------------------------------------
-- 目的：清空**早期那批已不可用的演示密钥数据**，为重新登记一批干净数据让路。
--
-- 为什么可以直接清空
-- ----------------
-- 这批密钥（26 条）全部是 `ms_v1` + `v0_random_sscl_domain` 签发的：
--   * 用户侧本地份额 `u` 从未持久化，用户也没有保存过 `d_a`，
--     所以它们**从解密角度本来就不可用** —— 不是故障，是密钥隔离设计生效的表现；
--   * SSCL 域参数当时每进程随机，客户端插值对不上；
--   * 遗漏的 `ua` 还被多把密钥共用。
-- 既然都是可重新生成的演示数据，保留它们只会让 P3 的端到端验证挑到死数据，
-- 因此选择清空后重新登记，而不是逐条标记为 legacy。
--
-- ⚠️ 与 `23_*.sql` 的关系
-- ----------------------
-- `23_*.sql` 把存量记录标成了 `legacy_unusable`。如果之后执行了本脚本，
-- 那一列在数据上就"空了"（没有行再带该状态）—— 但**机制保留**：
-- `key_material_state` / `ms_key_id` / `algorithm_version` 三列仍然存在，
-- 新登记的数据一律是 `ms_v2` + `v1_derived_sscl_domain` + `active`。
-- 日后若再出现"用户丢失本地份额"的密钥，仍可用 `legacy_unusable` 如实标记。
--
-- 清空范围（保守）
-- --------------
--   * `keymanage`            —— 密钥材料本体，必须清（承载 ms_v1 版本标记）
--   * `key_operation_record` —— 与其绑定的操作日志（含基于旧材料的 Merkle 批次证明）
-- **不清** `key_distribute_record`：它不含密钥材料，且是工作台「分发状态分布」
--   图表的数据源（计划 §3.6.5 要求图表必须有数据）；该表本身将在 P5 随旧分发链路一并删除。
--
-- 幂等：DELETE，可重复执行。
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 1. 清空密钥材料与绑定日志
-- ---------------------------------------------------------------------------
-- 先删日志再删密钥：日志里 key_id 指向 keymanage，先删主体会留下悬空引用。
DELETE FROM key_operation_record;
DELETE FROM keymanage;

-- 清理测试残留的权限申请（无真实审批价值；新流程从零开始更干净）
DELETE FROM permission_request;

-- ---------------------------------------------------------------------------
-- 2. 自检
-- ---------------------------------------------------------------------------
SELECT 'keymanage 残留（应为 0）' AS check_item, COUNT(*) AS actual FROM keymanage;
SELECT 'key_operation_record 残留（应为 0）' AS check_item, COUNT(*) AS actual FROM key_operation_record;

-- 注：这里原先还会统计 `key_distribute_record`（当时它是工作台「分发状态分布」的数据源）。
-- 该表已在 **P5** 中随旧分发链路一并删除，图表改读
-- `falcon_kds.dvadmin_pqkds_distribution_batches`，因此本脚本不再引用它 ——
-- 否则在全新库上重跑会直接报"表不存在"，让一个好端端的迁移脚本变成坏的。

-- 版本化三列仍然存在（机制保留，只是当下没有行携带 legacy 状态）
SELECT COLUMN_NAME
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'keymanage'
  AND COLUMN_NAME IN ('ms_key_id', 'algorithm_version', 'key_material_state');