-- 34_rename_pool_to_preallocation.sql
-- -----------------------------------------------------------------------------
-- 阶段 6（文档 §7.1/§7.2）：把「密钥池」重定义为「预分配密钥池」。
--
-- 为什么要改名（不只是文案）
-- ------------------------
-- 「密钥池」这个名字会让人以为它是**长期密钥**的仓库，而实际上它存的是：
--   在实际业务会话建立之前，提前为指定节点对准备好的、
--   **尚未消费**的短期 SM4 安全分发资源。
--
-- 长期密钥（SM2/SSCL/Kyber/Falcon）由「节点密钥库 / 密钥查询」管理，
-- 不在这个池子里。名字不改清楚，使用者会以为能在池子里看到节点私钥，
-- 或者反过来以为长期密钥消失在了池子里。
--
-- 只改展示名，不动 path/component —— 那会打断既有书签与前端 loadView 解析。
--
-- 幂等：UPDATE ... WHERE，可重复执行。
-- =============================================================================

SET NAMES utf8mb4;

UPDATE sys_menu
SET menu_name = '预分配密钥池',
    remark = '阶段6 重定义：仅管理尚未消费的短期 SM4 预分配资源，不存放节点长期私钥'
WHERE menu_id = 9104;

-- 父目录「分发与区块链」的备注也点明边界，避免后来者按旧理解使用
UPDATE sys_menu
SET remark = '分发模块与区块链相关页面（内嵌 /distribute/）；其下「预分配密钥池」只存短期 SM4 资源'
WHERE menu_id = 9100 AND remark NOT LIKE '%只存短期 SM4%';

-- ---------------------------------------------------------------------------
-- 自检
-- ---------------------------------------------------------------------------
SELECT '菜单改名结果' AS check_item, menu_id, menu_name, path, component
FROM sys_menu WHERE menu_id = 9104;