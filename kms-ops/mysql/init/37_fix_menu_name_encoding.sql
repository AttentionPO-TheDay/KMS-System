-- 修复 30_*.sql 造成的菜单名**双重编码**（2026-09-28）。
--
-- 事故经过
-- --------
-- `30_port_user_pages_into_console.sql` 是唯一**漏写 `SET NAMES utf8mb4`**
-- 的迁移脚本（31-36 都有）。用管道导入时客户端按默认单字节字符集解析文件里
-- 的中文，再以 utf8mb4 存储，于是「工作台」被存成 `C3A5C2B7C2A5...`——
-- 即 UTF-8 字节被逐字节当 Latin1 再编码一次。前端渲染出来是「å·¥ä½œå°」。
--
-- 影响范围（已实测扫描确认，仅此 5 行）
-- -----------------------------------
--   9050 工作台 / 9051 我的日志 / 9052 密钥分发 / 9053 对称密钥 / 9054 生成密钥
-- 判定方式：HEX(LEFT(menu_name,1)) 落在 C3A5/C3A6/C3A7 等"UTF-8 首字节被
-- 二次编码"的区间。全表扫描后只有这 5 行命中，其它菜单（含 31-36 写入的）
-- 均为正常 UTF-8。
--
-- 修法
-- ----
-- 直接按 menu_id 重写正确的中文。**不试图"反转双重编码"** ——
-- 那需要 CONVERT 两次且依赖 sql_mode，容易在边缘字符上再错一次；
-- 这 5 个名字是已知常量，直接写死最稳、可读、可复核。
-- 名字与 30_*.sql 中的定义保持一致，改一处必须同步另一处。
--
-- 幂等：UPDATE ... WHERE menu_id = ?，可重复执行。
-- =============================================================================

SET NAMES utf8mb4;

UPDATE sys_menu SET menu_name = '工作台'   WHERE menu_id = 9050;
UPDATE sys_menu SET menu_name = '我的日志' WHERE menu_id = 9051;
UPDATE sys_menu SET menu_name = '密钥分发' WHERE menu_id = 9052;
UPDATE sys_menu SET menu_name = '对称密钥' WHERE menu_id = 9053;
UPDATE sys_menu SET menu_name = '生成密钥' WHERE menu_id = 9054;

-- ---------------------------------------------------------------------------
-- 自检
-- ---------------------------------------------------------------------------
SELECT '修复后的菜单名（应显示为正常中文）' AS check_item, menu_id, menu_name
FROM sys_menu WHERE menu_id BETWEEN 9050 AND 9054 ORDER BY menu_id;

-- 全表扫描：不应再有双重编码的行。期望为空集。
-- 判据：首字节落在 C3xx 区间 —— 正常中文的 UTF-8 首字节在 E4..E9，
-- 而"被二次编码"的会变成 C3xx（Ã 开头）。
SELECT '仍存在双重编码（应为空）' AS check_item, menu_id, menu_name
FROM sys_menu
WHERE HEX(LEFT(menu_name, 1)) IN ('C3A5','C3A6','C3A7','C3A8','C3A9','C3B0','C3B1','C3B2');
